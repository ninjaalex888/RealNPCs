// The times: what people in 1899, and in the epilogue's 1907, were really living through and talking of (Lex, 2026-11-03:
// "real events that were happening in 1899 in the USA that people in the frontier might be talking about, such as incoming
// presidential elections, the names of politicians at the time, the native americans nearby, and much more interesting
// history from that time period"). Each topic is a thing of its year, with the month it was in the papers from: what one
// person brings up (the openers; thoughts as well as talk), and how the other answers it by their own nature: for it, against
// it, or a shrug (MindTalk.cs chooses the stance from who they are: the lawful and the well-off take the government's side of
// a political question, the reckless and the poor Bryan's; the compassionate and the devout feel for people, the hard don't;
// the curious marvel at the new, the orderly grumble at it). All lines are original to this add-on; the facts are the
// period's own (the election of 1900, the war in the Philippines, Dewey's homecoming, the Klondike and Nome, the Boers, the
// reservations and the allotments, the trusts, the new machines, the yellow papers, Jeffries, the Maple Leaf Rag, the
// blizzard of February, the century turning, The Hague, Dreyfus, Georgia; and for 1907 Roosevelt, the Panic, Oklahoma, the
// white fleet, motorcars and flying machines, San Francisco, the Thaw trial, Monongah and Haywood, The Jungle, Taft and
// Bryan, the Cubs, Johnson and Cobb, Ellis Island, the old West gone, the suffrage women, Geronimo's book). The Wapiti are
// the game's own people up north; everything else is history. Plain C#, no game; checked by mindtest (TimesTest).
using System;
using System.Collections.Generic;
using System.Linq;

namespace EnrageWestworld.Core
{
    public sealed class TimesTopic
    {
        public string Key;        // "election", "natives"...
        public int Year;          // 1899 or 1907
        public int From;          // the month it was in the papers from (1: all year)
        public string Lean;       // politics | people | wonder: which side of someone decides their stance (MindTalk.Stance)
        public string[] Openers;  // what one person brings up (a thought as well)
        public string[] For;      // the other, taking its side (the government's, the people's, the marvel's)
        public string[] Against;  // the other, against it
        public string[] Shrug;    // the other, not much caring
        public int Until;         // the last month it was talked of (0: the year's end): Hobart alive until November (Run 3, item 2)
        public int Weight = 1;    // how much more often it comes up than one topic (2: who holds office; Lex, 2026-11-04)
        public string[] More;     // the second round's word from the one who brought it up: more on the subject, never the news told again (the review of Run 3, item 2); null, no second round
    }

    public static class Times
    {
        private static TimesTopic T(string key, int year, int from, string lean, string[] openers, string[] @for, string[] against, string[] shrug)
        {
            return new TimesTopic { Key = key, Year = year, From = from, Lean = lean, Openers = openers, For = @for, Against = against, Shrug = shrug };
        }

        /// A topic with its last month and its weight (Run 3, item 2: who holds office and how the country lives in 1899).
        private static TimesTopic TW(string key, int year, int from, int until, int weight, string lean, string[] openers, string[] @for, string[] against, string[] shrug, string[] more = null)
        {
            TimesTopic t = T(key, year, from, lean, openers, @for, against, shrug);
            t.Until = until;
            t.Weight = weight;
            t.More = more;
            return t;
        }

