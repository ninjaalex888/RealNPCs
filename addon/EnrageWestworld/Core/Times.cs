              new[] { "Names in a paper. Wheat's the same price whoever's in.",
                      "I couldn't name you three of them and I'm none the poorer." },
              new[] { "Bryan's to run a third time next year, they say. Third time lucky.",
                      "Fairbanks sits over the Senate and nobody notices. That's a vice president's lot." })
        };

        /// The topics of this year that were in the papers by this month (month 0: the whole year).
        public static List<TimesTopic> Of(int year, int month)
        {
            if (!InnerLife.Historical)
                return new List<TimesTopic>();   // [World] HistoricalAccuracy off: nobody talks of the times
            int y = year >= 1905 ? 1907 : 1899;
            return All.Where(t => t.Year == y && (month <= 0 || t.From <= month && (t.Until <= 0 || month <= t.Until))).ToList();
        }

        /// One topic of the year, by the seed; null when none fits the month.
        public static TimesTopic Pick(int year, int month, string seed)
        {
            List<TimesTopic> fit = Of(year, month);
            if (fit.Count == 0)
                return null;
            int total = 0;
            foreach (TimesTopic t in fit)
                total += Math.Max(1, t.Weight);
            int roll = Voice.Hash(seed + "times") % total;   // by weight: who holds office comes up twice as often (Run 3, item 2)
            foreach (TimesTopic t in fit)
            {
                roll -= Math.Max(1, t.Weight);
                if (roll < 0)
                    return t;
            }
            return fit[fit.Count - 1];
        }

        /// What one person brings up of the times, as a thought or the start of a talk; null when nothing fits the month.
        public static string Opener(int year, int month, string seed, string town)
        {
            TimesTopic t = Pick(year, month, seed);
            return t == null ? null : Fill(Voice.Pick(seed + "open", t.Openers), town);
        }

        /// Every opener of the year, for the thoughts' era pool (InnerLife.Days.cs) and the tests.
        public static IEnumerable<string> Openers(int year, int month)
        {
            return Of(year, month).SelectMany(t => t.Openers);
        }

        /// The other's answer by their stance: "for", "against" or "shrug".
        public static string Reply(TimesTopic t, string stance, string seed, string town)
        {
            string[] pool = stance == "for" ? t.For : stance == "against" ? t.Against : t.Shrug;
            return Fill(Voice.Pick(seed + "reply" + stance, pool), town);
        }

        /// The town's name where a line names one.
        public static string Fill(string line, string town)
        {
            return line == null ? null : line.Replace("{town}", string.IsNullOrEmpty(town) ? "town" : town);
        }

        /// Every line, for the tests.
        public static IEnumerable<string> AllLines()
        {
            return All.SelectMany(t => t.Openers.Concat(t.For).Concat(t.Against).Concat(t.Shrug).Concat(t.More ?? new string[0]));
        }
    }
